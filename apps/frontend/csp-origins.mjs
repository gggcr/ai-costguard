// Where the browser may send requests (CSP connect-src): this origin, Keycloak and, when the API lives elsewhere, the
// API. Both addresses are baked into the bundle at build time (VITE_KEYCLOAK_URL, VITE_API_URL), so the policy is
// made from the same values in the same build: `node csp-origins.mjs > csp-connect.conf` writes the nginx map that
// security-headers.conf reads as $csp_connect.

/** The CSP sources for these build variables: origins only, so a path in a URL cannot narrow or break the rule. */
export function connectSources(env) {
  const sources = ["'self'"];
  for (const name of ['VITE_KEYCLOAK_URL', 'VITE_API_URL']) {
    const value = (env[name] ?? '').trim();
    if (!value) continue;
    let origin;
    try {
      origin = new URL(value).origin;
    } catch {
      throw new Error(`${name} is not an absolute URL: ${value}`);
    }
    if (!/^https?:\/\/[A-Za-z0-9.-]+(:\d+)?$/.test(origin)) {
      throw new Error(`${name} has an origin CSP cannot name: ${origin}`);
    }
    if (!sources.includes(origin)) sources.push(origin);
  }
  return sources.join(' ');
}

/** The nginx include: a map in the http block, the only place a value for every location can come from. */
export function nginxMap(env) {
  return `# Generated by csp-origins.mjs at build time; see security-headers.conf.\n`
    + `map $host $csp_connect {\n    default "${connectSources(env)}";\n}\n`;
}

// run as a script (the Dockerfile), not imported (the test)
if (process.argv[1]?.endsWith('csp-origins.mjs')) {
  process.stdout.write(nginxMap({
    VITE_KEYCLOAK_URL: process.env.VITE_KEYCLOAK_URL ?? 'http://localhost:8180',
    VITE_API_URL: process.env.VITE_API_URL,
  }));
}
