"""TypeScript types from the OpenAPI specs, so the frontend and the SDK cannot drift from the API.

    python tools/codegen/openapi_ts.py           # writes apps/frontend/src/api/generated/<spec>.ts
    python tools/codegen/openapi_ts.py --check   # fails if a generated file is out of date (CI)

Every schema of components/schemas becomes an exported type; operations become a map from operationId to the
method and path, which keeps the paths in one place. The specs come from the code (OpenApiContractTest), so the
chain is: Java records -> schemas/openapi/*.yaml -> these files.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
SPECS = {"core": ROOT / "schemas/openapi/core.yaml", "gateway": ROOT / "schemas/openapi/gateway.yaml"}
OUT = ROOT / "apps/frontend/src/api/generated"
HEADER = "// Generated by tools/codegen/openapi_ts.py from {spec}. Do not edit: run `make codegen`.\n\n"


def name_of(ref: str) -> str:
    return ref.rsplit("/", 1)[-1]


def ts(schema: dict, indent: str = "") -> str:
    if "$ref" in schema:
        return name_of(schema["$ref"])
    for combo, sep in (("oneOf", " | "), ("anyOf", " | "), ("allOf", " & ")):
        if combo in schema:
            return "(" + sep.join(ts(s, indent) for s in schema[combo]) + ")"
    if "enum" in schema:
        return " | ".join(f'"{v}"' if isinstance(v, str) else str(v) for v in schema["enum"])
    kind = schema.get("type")
    if kind == "array":
        inner = ts(schema.get("items", {}), indent)
        return f"Array<{inner}>"
    if kind in ("integer", "number"):
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "string":
        return "string"
    if kind == "object" or "properties" in schema:
        props = schema.get("properties", {})
        if not props:
            extra = schema.get("additionalProperties")
            return f"Record<string, {ts(extra, indent) if isinstance(extra, dict) else 'unknown'}>"
        required = set(schema.get("required", []))
        lines = []
        for prop, sub in props.items():
            key = prop if re.fullmatch(r"[A-Za-z_$][\w$]*", prop) else f'"{prop}"'
            optional = "" if prop in required else "?"
            fmt = sub.get("format") if isinstance(sub, dict) else None
            note = f"  // {fmt}" if fmt in ("uuid", "date", "date-time") else ""
            lines.append(f"{indent}  {key}{optional}: {ts(sub, indent + '  ')};{note}")
        return "{\n" + "\n".join(lines) + f"\n{indent}}}"
    return "unknown"


def generate(spec_name: str, spec: dict) -> str:
    out = [HEADER.format(spec=f"schemas/openapi/{spec_name}.yaml")]
    for name, schema in sorted(spec.get("components", {}).get("schemas", {}).items()):
        if "description" in schema:
            out.append(f"/** {schema['description'].strip()} */\n")
        out.append(f"export type {name} = {ts(schema)};\n\n")
    ops = []
    for path, methods in sorted(spec.get("paths", {}).items()):
        for method, op in sorted(methods.items()):
            if isinstance(op, dict) and "operationId" in op:
                ops.append((op.get("tags", ["api"])[0], op["operationId"], method.upper(), path))
    out.append("export const operations = {\n")
    seen: set[str] = set()
    for tag, op_id, method, path in ops:
        key = re.sub(r"\W", "", tag[:1].lower() + tag[1:]) + op_id[:1].upper() + op_id[1:]
        while key in seen:
            key += "_"
        seen.add(key)
        out.append(f'  {key}: {{ method: "{method}", path: "{path}" }},\n')
    out.append("} as const;\n")
    return "".join(out)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    stale = []
    for name, path in SPECS.items():
        text = generate(name, yaml.safe_load(path.read_text("utf-8")))
        target = OUT / f"{name}.ts"
        if args.check:
            if not target.exists() or target.read_text("utf-8") != text:
                stale.append(str(target.relative_to(ROOT)))
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text, "utf-8", newline="\n")
    if stale:
        print("Out of date, run `make codegen`: " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
